use crate::core::errors::{PdownError, Result};
use crate::core::models::{ChangeItem, ChangePlan, MirrorDefinition, ProviderStatus};
use crate::core::provider::Provider;
use crate::system::filesystem::generate_diff;
use std::collections::HashMap;
use std::env;
use std::fs;
use std::path::{Path, PathBuf};

pub const MARKER_START_GRADLE_TIMEOUT: &str = "# >>> Managed by pdown [Gradle Timeouts] >>>";
pub const MARKER_END_GRADLE_TIMEOUT: &str = "# <<< Managed by pdown [Gradle Timeouts] <<<";

pub struct GradleProvider;

impl GradleProvider {
    pub fn gradle_user_home() -> PathBuf {
        if let Ok(val) = env::var("GRADLE_USER_HOME") {
            if !val.trim().is_empty() {
                return PathBuf::from(val);
            }
        }
        let home = env::var("HOME")
            .or_else(|_| env::var("USERPROFILE"))
            .unwrap_or_else(|_| ".".to_string());
        PathBuf::from(home).join(".gradle")
    }

    pub fn init_d_dir() -> PathBuf {
        Self::gradle_user_home().join("init.d")
    }

    pub fn mirror_init_script_path() -> PathBuf {
        Self::init_d_dir().join("pdown-mirror.gradle")
    }

    pub fn gradle_properties_path() -> PathBuf {
        Self::gradle_user_home().join("gradle.properties")
    }

    /// Render safe init.gradle script with separate ecosystem rewrite blocks.
    pub fn render_init_script(
        maven_central: Option<&str>,
        google_maven: Option<&str>,
        gradle_plugins: Option<&str>,
    ) -> String {
        let mc = maven_central
            .map(|u| format!("\"{u}\""))
            .unwrap_or_else(|| "null".into());
        let gm = google_maven
            .map(|u| format!("\"{u}\""))
            .unwrap_or_else(|| "null".into());
        let gp = gradle_plugins
            .map(|u| format!("\"{u}\""))
            .unwrap_or_else(|| "null".into());

        format!(
            r#"// >>> Managed by pdown [Gradle Mirror] >>>
// Generated by PackageDownloader 2.0 (pdown)
// Safely redirects upstream repositories without corrupting unrelated repositories.

def MAVEN_CENTRAL_MIRROR = {mc}
def GOOGLE_MAVEN_MIRROR = {gm}
def GRADLE_PLUGINS_MIRROR = {gp}

def rewriteRepo = {{ repo ->
    if (repo instanceof org.gradle.api.artifacts.repositories.MavenArtifactRepository) {{
        def rawUrl = repo.url?.toString()
        if (!rawUrl) return
        def url = rawUrl.trim().replaceAll('/+$', '') + '/'

        if (MAVEN_CENTRAL_MIRROR && (url == "https://repo.maven.apache.org/maven2/" || url == "https://repo1.maven.org/maven2/")) {{
            repo.setUrl(uri(MAVEN_CENTRAL_MIRROR))
        }} else if (GOOGLE_MAVEN_MIRROR && (url == "https://dl.google.com/dl/android/maven2/" || url == "https://maven.google.com/")) {{
            repo.setUrl(uri(GOOGLE_MAVEN_MIRROR))
        }} else if (GRADLE_PLUGINS_MIRROR && url == "https://plugins.gradle.org/m2/") {{
            repo.setUrl(uri(GRADLE_PLUGINS_MIRROR))
        }}
    }}
}}

gradle.allprojects {{
    buildscript {{
        repositories {{ all {{ rewriteRepo(it) }} }}
    }}
    repositories {{
        all {{ rewriteRepo(it) }}
    }}
}}

gradle.settingsEvaluated {{ settings ->
    try {{
        if (settings.pluginManagement?.repositories) {{
            settings.pluginManagement.repositories.all {{ rewriteRepo(it) }}
        }}
    }} catch (Throwable t) {{
        logger.info("pdown [Gradle Init]: pluginManagement repositories not accessible: ${{t.message}}")
    }}
    try {{
        if (settings.dependencyResolutionManagement?.repositories) {{
            settings.dependencyResolutionManagement.repositories.all {{ rewriteRepo(it) }}
        }}
    }} catch (Throwable t) {{
        logger.info("pdown [Gradle Init]: dependencyResolutionManagement repositories not accessible: ${{t.message}}")
    }}
}}
// <<< Managed by pdown [Gradle Mirror] <<<
"#
        )
    }

    pub fn plan_properties_update(path: &Path) -> Result<ChangeItem> {
        let old_content = if path.exists() {
            Some(fs::read_to_string(path)?)
        } else {
            None
        };

        let payload = format!(
            "{}\nsystemProp.org.gradle.internal.http.connectionTimeout=120000\nsystemProp.org.gradle.internal.http.socketTimeout=120000\n{}",
            MARKER_START_GRADLE_TIMEOUT, MARKER_END_GRADLE_TIMEOUT
        );

        let new_content = match &old_content {
            Some(existing) => {
                if let (Some(s), Some(e)) = (
                    existing.find(MARKER_START_GRADLE_TIMEOUT),
                    existing.find(MARKER_END_GRADLE_TIMEOUT),
                ) {
                    let end_pos = e + MARKER_END_GRADLE_TIMEOUT.len();
                    format!("{}{}{}", &existing[..s], payload, &existing[end_pos..])
                } else {
                    format!("{existing}\n\n{payload}\n")
                }
            }
            None => format!("{payload}\n"),
        };

        let diff = generate_diff(
            old_content.as_deref().unwrap_or(""),
            &new_content,
            &path.to_string_lossy(),
        );

        Ok(ChangeItem::FileWrite {
            path: path.to_path_buf(),
            old_content,
            new_content,
            diff,
        })
    }

    pub fn plan_properties_revert(path: &Path) -> Result<Option<ChangeItem>> {
        if !path.exists() {
            return Ok(None);
        }

        let old_content = fs::read_to_string(path)?;
        let new_content = if let (Some(s), Some(e)) = (
            old_content.find(MARKER_START_GRADLE_TIMEOUT),
            old_content.find(MARKER_END_GRADLE_TIMEOUT),
        ) {
            let end_pos = e + MARKER_END_GRADLE_TIMEOUT.len();
            let before = old_content[..s].trim_end();
            let after = old_content[end_pos..].trim_start();
            if before.is_empty() && after.is_empty() {
                String::new()
            } else if before.is_empty() {
                format!("{after}\n")
            } else if after.is_empty() {
                format!("{before}\n")
            } else {
                format!("{before}\n\n{after}\n")
            }
        } else {
            return Ok(None);
        };

        let diff = generate_diff(&old_content, &new_content, &path.to_string_lossy());

        Ok(Some(ChangeItem::FileWrite {
            path: path.to_path_buf(),
            old_content: Some(old_content),
            new_content,
            diff,
        }))
    }

    /// Update gradle/wrapper/gradle-wrapper.properties distributionUrl to point to mirror distribution.
    pub fn plan_wrapper_properties_update(
        path: &Path,
        dist_mirror_base: &str,
    ) -> Result<Option<ChangeItem>> {
        if !path.exists() {
            return Ok(None);
        }

        let old_content = fs::read_to_string(path)?;
        let mut lines: Vec<String> = old_content.lines().map(|s| s.to_string()).collect();
        let mut modified = false;

        for line in &mut lines {
            let trimmed = line.trim();
            if trimmed.starts_with("distributionUrl=") || trimmed.starts_with("distributionUrl =") {
                let parts: Vec<&str> = line.splitn(2, '=').collect();
                if parts.len() == 2 {
                    let current_val = parts[1].trim();
                    let unescaped = current_val.replace("\\:", ":");
                    let filename = unescaped.rsplit('/').next().unwrap_or("").trim();
                    if !filename.is_empty() && filename.ends_with(".zip") {
                        let new_url =
                            format!("{}/{}", dist_mirror_base.trim_end_matches('/'), filename);
                        let escaped_new_url = new_url.replace("://", "\\://");
                        let new_line = format!("distributionUrl={escaped_new_url}");
                        if *line != new_line {
                            *line = new_line;
                            modified = true;
                        }
                    }
                }
            }
        }

        if !modified {
            return Ok(None);
        }

        let mut new_content = lines.join("\n");
        if old_content.ends_with('\n') {
            new_content.push('\n');
        }

        let diff = generate_diff(&old_content, &new_content, &path.to_string_lossy());
        Ok(Some(ChangeItem::FileWrite {
            path: path.to_path_buf(),
            old_content: Some(old_content),
            new_content,
            diff,
        }))
    }

    /// Revert gradle/wrapper/gradle-wrapper.properties distributionUrl to upstream services.gradle.org.
    pub fn plan_wrapper_properties_revert(path: &Path) -> Result<Option<ChangeItem>> {
        if !path.exists() {
            return Ok(None);
        }

        let old_content = fs::read_to_string(path)?;
        let mut lines: Vec<String> = old_content.lines().map(|s| s.to_string()).collect();
        let mut modified = false;

        for line in &mut lines {
            let trimmed = line.trim();
            if trimmed.starts_with("distributionUrl=") || trimmed.starts_with("distributionUrl =") {
                let parts: Vec<&str> = line.splitn(2, '=').collect();
                if parts.len() == 2 {
                    let current_val = parts[1].trim();
                    let unescaped = current_val.replace("\\:", ":");
                    let filename = unescaped.rsplit('/').next().unwrap_or("").trim();
                    if !filename.is_empty() && filename.ends_with(".zip") {
                        let upstream_url =
                            format!("https\\://services.gradle.org/distributions/{filename}");
                        let new_line = format!("distributionUrl={upstream_url}");
                        if *line != new_line {
                            *line = new_line;
                            modified = true;
                        }
                    }
                }
            }
        }

        if !modified {
            return Ok(None);
        }

        let mut new_content = lines.join("\n");
        if old_content.ends_with('\n') {
            new_content.push('\n');
        }

        let diff = generate_diff(&old_content, &new_content, &path.to_string_lossy());
        Ok(Some(ChangeItem::FileWrite {
            path: path.to_path_buf(),
            old_content: Some(old_content),
            new_content,
            diff,
        }))
    }
}

impl Provider for GradleProvider {
    fn id(&self) -> &'static str {
        "gradle"
    }

    fn display_name(&self) -> &'static str {
        "Gradle & Maven Repositories"
    }

    fn is_supported(&self) -> bool {
        true
    }

    fn detect_current(&self) -> Result<ProviderStatus> {
        let script_path = Self::mirror_init_script_path();
        let is_configured = script_path.exists();

        let mut details = HashMap::new();
        details.insert(
            "init_script".to_string(),
            if is_configured {
                script_path.to_string_lossy().to_string()
            } else {
                "none (using upstream gradle defaults)".to_string()
            },
        );

        Ok(ProviderStatus {
            provider_id: self.id().to_string(),
            is_active: is_configured,
            current_endpoint: if is_configured {
                Some("managed via ~/.gradle/init.d/pdown-mirror.gradle".to_string())
            } else {
                None
            },
            details,
        })
    }

    fn plan_apply(&self, mirror: &MirrorDefinition) -> Result<ChangePlan> {
        let gradle_config = mirror.providers.gradle.as_ref().ok_or_else(|| {
            PdownError::InvalidConfig(format!("Mirror '{}' does not support Gradle", mirror.id))
        })?;

        if !gradle_config.enabled {
            return Err(PdownError::InvalidConfig(format!(
                "Gradle provider is disabled for mirror '{}'",
                mirror.id
            )));
        }

        let mut items = Vec::new();

        // 1. Plan writing init.d script
        let script_path = Self::mirror_init_script_path();
        let old_content = if script_path.exists() {
            Some(fs::read_to_string(&script_path)?)
        } else {
            None
        };

        let new_content = Self::render_init_script(
            gradle_config.maven_central_url.as_deref(),
            gradle_config.google_maven_url.as_deref(),
            gradle_config.gradle_plugins_url.as_deref(),
        );

        let diff = generate_diff(
            old_content.as_deref().unwrap_or(""),
            &new_content,
            &script_path.to_string_lossy(),
        );

        items.push(ChangeItem::FileWrite {
            path: script_path,
            old_content,
            new_content,
            diff,
        });

        // 2. Plan updating gradle.properties for timeouts
        let props_path = Self::gradle_properties_path();
        items.push(Self::plan_properties_update(&props_path)?);

        // 3. Plan updating project gradle/wrapper/gradle-wrapper.properties if present
        let local_wrapper = Path::new("gradle/wrapper/gradle-wrapper.properties");
        if local_wrapper.exists() {
            if let Some(ref dist_url) = gradle_config.distribution_url {
                if let Some(item) = Self::plan_wrapper_properties_update(local_wrapper, dist_url)? {
                    items.push(item);
                }
            }
        }

        Ok(ChangePlan {
            provider_id: self.id().to_string(),
            description: format!(
                "Configure Gradle init.d script, properties, and wrapper for mirror '{}'",
                mirror.id
            ),
            items,
        })
    }

    fn plan_revert(&self) -> Result<ChangePlan> {
        let mut items = Vec::new();

        // 1. Delete managed init script if it exists
        let script_path = Self::mirror_init_script_path();
        if script_path.exists() {
            let old_content = Some(fs::read_to_string(&script_path)?);
            items.push(ChangeItem::FileDelete {
                path: script_path,
                old_content,
            });
        }

        // 2. Revert gradle.properties timeouts
        let props_path = Self::gradle_properties_path();
        if let Some(item) = Self::plan_properties_revert(&props_path)? {
            items.push(item);
        }

        // 3. Revert local wrapper properties if present
        let local_wrapper = Path::new("gradle/wrapper/gradle-wrapper.properties");
        if local_wrapper.exists() {
            if let Some(item) = Self::plan_wrapper_properties_revert(local_wrapper)? {
                items.push(item);
            }
        }

        Ok(ChangePlan {
            provider_id: self.id().to_string(),
            description: "Remove managed Gradle init.d script and reset properties".to_string(),
            items,
        })
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_render_init_script_selective_endpoints() {
        let script = GradleProvider::render_init_script(
            Some("https://mirror-maven.runflare.com/maven2/"),
            None,
            None,
        );
        assert!(script.contains("https://mirror-maven.runflare.com/maven2/"));
        assert!(script.contains("def GOOGLE_MAVEN_MIRROR = null"));
        assert!(script.contains("if (MAVEN_CENTRAL_MIRROR &&"));
        assert!(
            script.contains("pdown [Gradle Init]: pluginManagement repositories not accessible")
        );
    }

    #[test]
    fn test_gradle_wrapper_properties_update_and_revert() {
        let tmp = tempfile::tempdir().unwrap();
        let wrapper_file = tmp.path().join("gradle-wrapper.properties");
        let initial_content = "distributionBase=GRADLE_USER_HOME\n\
distributionPath=wrapper/dists\n\
distributionUrl=https\\://services.gradle.org/distributions/gradle-8.5-bin.zip\n\
zipStoreBase=GRADLE_USER_HOME\n\
zipStorePath=wrapper/dists\n";
        fs::write(&wrapper_file, initial_content).unwrap();

        // 1. Plan and apply wrapper update
        let change = GradleProvider::plan_wrapper_properties_update(
            &wrapper_file,
            "https://maven.myket.ir/gradle/distributions/",
        )
        .unwrap()
        .expect("ChangeItem must be generated");

        if let ChangeItem::FileWrite { new_content, .. } = change {
            assert!(new_content.contains(
                "distributionUrl=https\\://maven.myket.ir/gradle/distributions/gradle-8.5-bin.zip"
            ));
            fs::write(&wrapper_file, &new_content).unwrap();
        } else {
            panic!("Expected FileWrite");
        }

        // 2. Plan and apply revert
        let revert = GradleProvider::plan_wrapper_properties_revert(&wrapper_file)
            .unwrap()
            .expect("Revert ChangeItem must be generated");

        if let ChangeItem::FileWrite { new_content, .. } = revert {
            assert!(new_content.contains(
                "distributionUrl=https\\://services.gradle.org/distributions/gradle-8.5-bin.zip"
            ));
        } else {
            panic!("Expected FileWrite on revert");
        }
    }
}
